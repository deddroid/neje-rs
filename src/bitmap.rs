//! 1-bit bitmaps as the engraver expects them (GDI+ layout).

use image::GrayImage;

/// Size of the BMP header: 14 (file) + 40 (info) + 8 (two-colour palette).
pub const BMP_HEADER_LEN: usize = 62;

/// Bytes per row of a 1-bit image, rounded up to 4 bytes like GDI+.
pub fn stride_1bpp(width: u32) -> usize {
    width.div_ceil(32) as usize * 4
}

/// Packs `img` row by row from the top, most significant bit = leftmost pixel; a bit is 1
/// where `is_one(pixel)` holds.
pub fn pack_1bpp(img: &GrayImage, is_one: impl Fn(u8) -> bool) -> Vec<u8> {
    let stride = stride_1bpp(img.width());
    let mut out = vec![0u8; stride * img.height() as usize];
    for (y, row) in img.rows().enumerate() {
        let line = &mut out[y * stride..(y + 1) * stride];
        for (x, px) in row.enumerate() {
            if is_one(px.0[0]) {
                line[x >> 3] |= 0x80 >> (x & 7);
            }
        }
    }
    out
}

/// Wraps already packed rows in a 1-bit BMP file (palette index 0 = black, 1 = white).
/// The V10 firmware receives the whole file. Resolution and colour counts are the values
/// GDI+ is assumed to write; the firmware almost certainly ignores them, since EzGraver
/// sends a different header generated by Qt and it works.
pub fn bmp_1bpp(width: u32, height: u32, rows: &[u8]) -> Vec<u8> {
    let image_len = stride_1bpp(width) * height as usize;
    assert_eq!(rows.len(), image_len, "packed rows do not match {width}x{height}");
    let file_len = (BMP_HEADER_LEN + image_len) as u32;
    let mut out = Vec::with_capacity(BMP_HEADER_LEN + image_len);
    out.extend_from_slice(b"BM");
    out.extend_from_slice(&file_len.to_le_bytes());
    out.extend_from_slice(&[0; 4]);
    out.extend_from_slice(&(BMP_HEADER_LEN as u32).to_le_bytes());
    out.extend_from_slice(&40u32.to_le_bytes());
    out.extend_from_slice(&(width as i32).to_le_bytes());
    out.extend_from_slice(&(height as i32).to_le_bytes());
    out.extend_from_slice(&1u16.to_le_bytes()); // planes
    out.extend_from_slice(&1u16.to_le_bytes()); // bits per pixel
    out.extend_from_slice(&0u32.to_le_bytes()); // no compression
    out.extend_from_slice(&(image_len as u32).to_le_bytes());
    out.extend_from_slice(&3780i32.to_le_bytes()); // 96 dpi
    out.extend_from_slice(&3780i32.to_le_bytes());
    out.extend_from_slice(&2u32.to_le_bytes()); // colours used
    out.extend_from_slice(&2u32.to_le_bytes()); // important colours
    out.extend_from_slice(&[0, 0, 0, 0, 255, 255, 255, 0]);
    out.extend_from_slice(rows);
    out
}

/// Decodes the image data the engraver received back into pixels (0 = burn). Used by the
/// simulator; `burn_bit` is the bit value that means "burn" (V10: 0, V2x/V30: 1).
pub fn unpack_1bpp(data: &[u8], width: u32, height: u32, burn_bit: u8) -> GrayImage {
    let stride = stride_1bpp(width);
    GrayImage::from_fn(width, height, |x, y| {
        let byte = data.get(y as usize * stride + (x as usize >> 3)).copied().unwrap_or(0);
        let bit = (byte >> (7 - (x & 7))) & 1;
        image::Luma([if bit == burn_bit { 0 } else { 255 }])
    })
}
